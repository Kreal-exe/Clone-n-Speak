def _entry(base):
    e = dict(base)
    e.setdefault("load_file", e["file"])   # the name audio-separator knows the model by (Demucs: its .yaml)
    files = _pins.STEMS.get(e["id"], []) if _pins is not None else []
    main = next((f for f in files if f["path"] == e["file"]), None)
    e["url"] = main["url"] if main else ""
    e["sha256"] = main["sha256"] if main else ""
    e["size"] = main["size"] if main else 0
    e["files"] = [f["path"] for f in files]
    return e


ALL = [_entry(b) for b in _BASE]
# What the app offers: verified models, and the unverified ones the user accepted.
CATALOG = [e for e in ALL if e["verified"] or e["accepted_by_user"]]
BY_ID = {e["id"]: e for e in CATALOG}


def get(model_id):
    return BY_ID.get(model_id)


def model_dir(root, model_id):
    """Where the installed files of a model live: the same folder cns_engines.weight_files uses."""
    return os.path.join(root, "stems", model_id)
