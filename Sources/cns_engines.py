def install(root, components_, uv, env, emit_fn, opener=None, python=PYTHON_VERSION):
    """Installs the components (and what they need) in catalog order. Returns the ids installed by this call;
    components that are already ready are skipped. emit_fn(event, **data): "status" {msg}, "progress" {value}."""
    cns_net.require_online("model_download")
    layout = read_layout(root)
    wanted = _closure(components_, layout)
    todo = [c for c in wanted if component_state(root, c, layout) != "ready"]
    os.makedirs(root, exist_ok=True)
    _check_disk(root, todo)
    uvenv = _uv_env(env)
    prog = _Progress(emit_fn, todo)
    done = []
    emit_fn("progress", value=0.0)
    for comp in todo:
        _clear_ready(root, comp)
        _mark_installing(root, comp)
        kind = comp["kind"]
        if kind == "env":
            data = _install_env(root, comp, uv, uvenv, emit_fn, prog, python)
        elif kind == "ytdlp":
            data = _install_ytdlp(root, comp, uv, uvenv, emit_fn, prog)
        elif kind == "applio":
            data = _install_applio(root, comp, emit_fn, prog, opener)
        elif kind in ("weights", "stems"):
            data = _install_weights(root, comp, emit_fn, prog, opener)
        elif kind == "seedvc":
            data = _install_seedvc(root, comp, uvenv, emit_fn, prog, opener)
        else:
            data = _install_edge(root, comp, uv, uvenv, emit_fn, prog, python)
        _write_ready(root, comp, data)
        prog.stage_at(comp["id"], 1.0)
        done.append(comp["id"])
    emit_fn("progress", value=1.0)
    return done


def update_ytdlp(root, uv, env, emit_fn):
    if not is_ready(root, "pro-env"):
        raise EngineError("Install the pro engines first.")
    comp = _by_id(read_layout(root))["ytdlp"]
    prog = _Progress(emit_fn, [comp])
    _run_uv([uv, "pip", "install", "--python", python_path(root, "pro-env"), "-U", "yt-dlp"], _uv_env(env), emit_fn,
            prog, "ytdlp", 0.0, 1.0, "yt-dlp…")
    _write_ready(root, comp, {"version": None})
    return ytdlp_version(root)


