def _tree_bytes(path):
    if os.path.islink(path):
        return 0
    if os.path.isfile(path):
        return os.path.getsize(path)
    total = 0
    for dirpath, dirs, files in os.walk(path):
        for n in files:
            try:
                total += os.lstat(os.path.join(dirpath, n)).st_size
            except OSError:
                pass
    return total


def _delete(path):
    n = _tree_bytes(path)
    if os.path.islink(path) or os.path.isfile(path):
        _remove(path)
    else:
        shutil.rmtree(path, ignore_errors=True)
    return n


def uninstall(root, components_):
    """Removes components and returns the bytes freed. pro-env (and applio-env) cannot go while something that runs
    in it is installed, unless that is removed in the same call. Trained voices (training/) are never touched."""
    layout = read_layout(root)
    table = _by_id(layout)
    for cid in components_:
        if cid not in table:
            raise EngineError("Unknown engine component: %s" % cid)
    removing = set(components_)
    for cid in components_:
        users = [c["id"] for c in components(layout) if cid in c["deps"] and c["id"] not in removing
                 and component_state(root, c, layout) != "notinstalled"]
        if users:
            raise EngineError("%s is needed by %s. Remove those first." % (table[cid]["title"], ", ".join(users)))
    freed = 0
    for cid in components_:
        comp = table[cid]
        _clear_ready(root, comp)
        kind = comp["kind"]
        if kind in ("weights", "stems"):
            for path, _ in weight_files(root, comp):
                freed += _delete(path) + _delete(path + ".part")
            freed += _delete(state_dir(root, comp))
        elif kind == "ytdlp":
            freed += _delete(state_dir(root, comp))
            freed += _pip_uninstall_ytdlp(root)
        elif kind == "applio":
            freed += _delete(applio_dir(root)) + _delete(applio_dir(root) + ".new")
        else:
            freed += _delete(state_dir(root, comp))
    return freed


def _pip_uninstall_ytdlp(root):
    lib = os.path.join(env_dir(root, "pro-env"), ".venv", "lib")
    freed = 0
    try:
        for py in os.listdir(lib):
            site = os.path.join(lib, py, "site-packages")
            for name in os.listdir(site) if os.path.isdir(site) else ():
                if name.lower().startswith("yt_dlp"):
                    freed += _delete(os.path.join(site, name))
    except OSError:
        pass
    return freed


