# ----------------------------------------------------------------------------------------------- the component table

def _component(cid, title, kind, download, disk, license_, optional=True, deps=()):
    return {"id": cid, "title": title, "kind": kind, "download_bytes": download, "disk_bytes": disk,
            "license": license_, "optional": optional, "deps": tuple(deps)}


def read_layout(root):
    try:
        with open(os.path.join(root, "engines.json")) as f:
            layout = json.load(f).get("layout")
    except (OSError, ValueError, AttributeError):
        return LAYOUT_DEFAULT
    return layout if layout in ("shared", "split") else LAYOUT_DEFAULT


