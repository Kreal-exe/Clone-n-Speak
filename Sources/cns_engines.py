def _pages(text, label):
    for line in text.splitlines():
        if line.startswith(label):
            digits = "".join(ch for ch in line.split(":", 1)[1] if ch.isdigit())
            return int(digits) if digits else 0
    return 0


def memory_report(vm_stat_text, swap_text, physical_bytes):
    """free_gb = free + inactive + purgeable + speculative pages; swap_used_gb from `sysctl vm.swapusage`."""
    page = 16384
    first = vm_stat_text.splitlines()[0] if vm_stat_text.strip() else ""
    if "page size of" in first:
        digits = "".join(ch for ch in first.split("page size of", 1)[1] if ch.isdigit())
        page = int(digits) if digits else page
    free_pages = sum(_pages(vm_stat_text, "Pages " + k + ":") for k in ("free", "inactive", "purgeable", "speculative"))
    free_gb = free_pages * page / float(GB)
    swap_gb = 0.0
    if "used" in swap_text:
        tail = swap_text.split("used", 1)[1].lstrip(" =")
        num = ""
        for ch in tail:
            if ch.isdigit() or ch == ".":
                num += ch
            else:
                unit = ch
                break
        else:
            unit = "M"
        if num:
            swap_gb = float(num) * {"K": 1 / 1024.0 / 1024.0, "M": 1 / 1024.0, "G": 1.0, "T": 1024.0}.get(unit.upper(), 1 / 1024.0)
    pressure = "normal"
    if free_gb < 3 or swap_gb >= 1:
        pressure = "warning"
    if free_gb < 1 or swap_gb >= 4:
        pressure = "critical"
    return {"free_gb": round(free_gb, 2), "swap_used_gb": round(swap_gb, 2), "pressure": pressure,
            "physical_gb": round(physical_bytes / float(GB), 1)}


def system_memory():
    """memory_report() of this Mac."""
    def run(args):
        return subprocess.run(args, capture_output=True, text=True, timeout=10).stdout
    vm = run(["/usr/bin/vm_stat"])
    swap = run(["/usr/sbin/sysctl", "vm.swapusage"])
    phys = int(run(["/usr/sbin/sysctl", "-n", "hw.memsize"]).strip() or 0)
    return memory_report(vm, swap, phys)


def _sb_quote(path):
    if not os.path.isabs(path) or any(ord(c) < 32 for c in path):
        raise EngineError("Sandbox paths must be absolute and printable: %r" % path)
    return '"' + path.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sandbox_profile(deny_network, write_roots):
    """A sandbox-exec profile: everything allowed, network optionally denied, writes only below write_roots."""
    lines = ["(version 1)", "(allow default)"]
    if deny_network:
        lines.append("(deny network*)")
    lines.append("(deny file-write*)")
    for r in write_roots:
        _sb_quote(r)   # absolute and printable, before it is resolved
    allow = ['(literal "/dev/null")'] + ["(subpath %s)" % _sb_quote(os.path.realpath(r)) for r in write_roots]
    lines.append("(allow file-write* %s)" % " ".join(allow))
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------------------------------------------- CLI

def _parse(argv):
    ap = argparse.ArgumentParser(prog="cns_engines.py")
    ap.add_argument("command", choices=["status", "install", "weights", "uninstall", "update-ytdlp", "memory"])
    ap.add_argument("--root")
    ap.add_argument("--components", default="")
    ap.add_argument("--uv")
    return ap.parse_args(argv)


def _request(args):
    if args.root:
        req = {"root": args.root, "components": [c for c in args.components.split(",") if c]}
        if args.uv:
            req["uv"] = args.uv
        return req
    if args.command == "memory":
        return {}
    return cns_proto.read_request()


def main(argv=None):
    args = _parse(sys.argv[1:] if argv is None else argv)
    cns_proto.install_stdout_guard()
    try:
        req = _request(args)
        root = req.get("root")
        if args.command == "memory":
            cns_proto.result(**dict(system_memory(), peak_gb=PEAK_GB))
            return 0
        if not root:
            raise EngineError("No engines folder given.")
        root = os.path.abspath(root)
        emit = lambda event, **kw: cns_proto.emit(event, **kw)  # noqa: E731
        uv = req.get("uv") or os.environ.get("CNS_UV") or shutil.which("uv") or "uv"
        if args.command == "status":
            cns_proto.result(**status(root))
        elif args.command in ("install", "weights"):
            comps = list(req.get("components") or [])
            if args.command == "weights":
                table = _by_id(read_layout(root))
                comps = [c for c in comps if c in table and table[c]["kind"] in ("weights", "stems")] or ["rvc-core"]
            done = install(root, comps, uv, req.get("env"), emit)
            cns_proto.result(installed=done, **status(root))
        elif args.command == "uninstall":
            cns_proto.result(freed_bytes=uninstall(root, list(req.get("components") or [])), **status(root))
        else:
            cns_proto.result(ytdlp_version=update_ytdlp(root, uv, req.get("env"), emit))
        return 0
    except (EngineError, cns_proto.ProtoError, cns_net.OfflineError) as e:
        cns_proto.fail(str(e))
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
