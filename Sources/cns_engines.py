class _Progress:
    """Overall 0..1 progress over the components being installed, weighted by download size."""

    def __init__(self, emit_fn, comps):
        self.emit_fn = emit_fn
        self.map = cns_proto.ProgressMap([(c["id"], max(c["download_bytes"], 1)) for c in comps]) if comps else None
        self.stage = None

    def stage_at(self, cid, frac):
        self.emit_fn("progress", value=self.map.at(cid, frac))


def _closure(requested, layout):
    table = _by_id(layout)
    want = set()

    def add(cid):
        if cid not in table:
            raise EngineError("Unknown engine component: %s" % cid)
        for d in table[cid]["deps"]:
            add(d)
        want.add(cid)
    for cid in requested:
        add(cid)
    return [c for c in components(layout) if c["id"] in want]


def _kill_group(p):
    """Kills the child's whole process group (it was started with start_new_session)."""
    try:
        os.killpg(p.pid, signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        try:
            p.kill()
        except OSError:
            pass


def _run_group(cmd, timeout, **kw):
    """subprocess.run in its own session: on timeout the whole process group dies (a bare kill() would leave the
    grandchildren of uv / python running), then TimeoutExpired is raised."""
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, start_new_session=True, **kw)
    try:
        out, err = p.communicate(timeout=timeout)
    except BaseException:
        _kill_group(p)
        try:
            p.communicate(timeout=5)
        except (subprocess.TimeoutExpired, OSError, ValueError):
            pass
        raise
    return subprocess.CompletedProcess(cmd, p.returncode, out, err)


def _run_uv(args, env, emit_fn, prog, cid, lo, hi, what):
    emit_fn("status", msg=what)
    try:
        p = subprocess.Popen(args, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
                             start_new_session=True)
    except OSError as e:
        raise EngineError("Could not start the installer (%s)." % e)
    n = 0
    try:
        for line in p.stdout:
            n += 1
            print(line.rstrip(), file=sys.stderr, flush=True)
            prog.stage_at(cid, lo + (hi - lo) * (1 - 0.97 ** n))
        code = p.wait()
    except BaseException:
        _kill_group(p)
        raise
    if code:
        raise EngineError("Could not install %s — see the log, then press Install again." % what.rstrip("…. "))


def _check_disk(root, comps):
    need = sum(c["disk_bytes"] for c in comps)
    probe = root
    while not os.path.exists(probe):
        probe = os.path.dirname(probe)
    free = shutil.disk_usage(probe).free
    if free < need * 1.1:
        raise EngineError("Not enough free disk space: %.1f GB needed, %.1f GB free." % (need / 1e9, free / 1e9))


_SAFE_PATH = "/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin:/usr/local/bin"
_SECRET_WORDS = ("TOKEN", "KEY", "SECRET", "PASSWORD", "CREDENTIAL", "AUTH")


_PASS_THROUGH = ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "NO_PROXY", "http_proxy", "https_proxy", "all_proxy",
                 "no_proxy", "SSL_CERT_FILE", "REQUESTS_CA_BUNDLE", "UV_HTTP_TIMEOUT")


def _blocked_env(name):
    up = name.upper()
    return up.startswith(("UV_INDEX", "UV_EXTRA_INDEX", "UV_DEFAULT_INDEX", "PIP_", "HF_TOKEN", "HUGGING")) or any(
        w in up for w in _SECRET_WORDS)


def _safe_env(root, extra=None):
    """The environment of every child process (uv, pip builds, Seed-VC): built from a short allowlist, never copied from
    ours, so index overrides (UV_INDEX*, PIP_*), tokens and API keys in the app's environment cannot reach it. The
    caller's explicit keys are added, minus index overrides and anything that looks like a secret."""
    env = {"PATH": _SAFE_PATH, "HOME": os.environ.get("HOME", os.path.expanduser("~")),
           "LANG": os.environ.get("LANG", "en_US.UTF-8"), "PYTHONNOUSERSITE": "1", "PYTHONDONTWRITEBYTECODE": "1",
           "UV_CACHE_DIR": os.path.join(root, ".uv-cache"), "UV_NO_CONFIG": "1"}
    if os.environ.get("TMPDIR"):
        env["TMPDIR"] = os.environ["TMPDIR"]
    for k in _PASS_THROUGH:   # network settings the install needs behind a proxy or a corporate CA
        if os.environ.get(k) and not _blocked_env(k):
            env[k] = os.environ[k]
    for k, v in (extra or {}).items():
        if not _blocked_env(str(k)):
            env[str(k)] = str(v)
    return env


def _pip(uv, py, *args, no_binary=()):
    """uv pip install, wheels only except the documented packages in no_binary."""
    cmd = [uv, "pip", "install", "--python", py, "--only-binary", ":all:"]
    for pkg in no_binary:
        cmd += ["--no-binary", pkg]
    return cmd + list(args)


