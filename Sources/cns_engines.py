# ----------------------------------------------------------------------------------------------- the component table

def _component(cid, title, kind, download, disk, license_, optional=True, deps=()):
    return {"id": cid, "title": title, "kind": kind, "download_bytes": download, "disk_bytes": disk,
            "license": license_, "optional": optional, "deps": tuple(deps)}


def read_layout(root):
    try:
        with open(os.path.join(root, "engines.json")) as f:
            layout = json.load(f).get("layout")
    except (OSError, ValueError, AttributeError):
        return LAYOUT_DEFAULT
    return layout if layout in ("shared", "split") else LAYOUT_DEFAULT


def components(layout=LAYOUT_DEFAULT):
    """The catalog, in install order. Stem models are added by cns_pins.STEMS (Task 7.5)."""
    split = layout == "split"
    env_dep = ("applio-env",) if split else ("pro-env",)
    table = [
        _component("pro-env", "Python environment (PyTorch)", "env", 1_300_000_000, 3_500_000_000, "Various (open source)"),
    ]
    if split:
        table.append(_component("applio-env", "Applio environment (PyTorch 2.11)", "env", 1_300_000_000, 3_500_000_000,
                                "Various (open source)"))
    table += [
        _component("ytdlp", "yt-dlp", "ytdlp", 20_000_000, 60_000_000, "Unlicense", deps=("pro-env",)),
        _component("applio", "Applio voice engine", "applio", 15_000_000, 30_000_000, "MIT", deps=env_dep),
    ]
    for cid, title, lic in (("rvc-core", "Voice models: pitch and content analysis", "MIT"),
                            ("rvc-fcpe", "Faster pitch detector", "MIT"),
                            ("rvc-train-32k", "Training base, 32 kHz", "MIT"),
                            ("rvc-train-40k", "Training base, 40 kHz", "MIT"),
                            ("rvc-train-48k", "Training base, 48 kHz", "MIT")):
        size = sum(e["size"] for e in pins.WEIGHTS[cid])
        table.append(_component(cid, title, "weights", size, size, lic, optional=cid != "rvc-core"))
    table.append(_component("seedvc", "Seed-VC", "seedvc", 1_600_000_000, 2_000_000_000, "GPL-3.0", deps=("pro-env",)))
    for sid in sorted(pins.STEMS):
        size = sum(e["size"] for e in pins.STEMS[sid])
        table.append(_component("stems-" + sid, "Stem model " + sid, "stems", size, size, "See the model's page",
                                deps=("pro-env",)))
    table.append(_component("edge", "Edge text-to-speech", "edge", 30_000_000, 80_000_000, "LGPL-3.0"))
    return table


def _by_id(layout):
    return {c["id"]: c for c in components(layout)}


def _entries(comp):
    """The pinned weight files of a weights/stems component."""
    if comp["kind"] == "weights":
        return pins.WEIGHTS[comp["id"]]
    if comp["kind"] == "stems":
        return pins.STEMS[comp["id"][len("stems-"):]]
    return []


# ---------------------------------------------------------------------------------------------------------- locations

def env_dir(root, cid):
    return os.path.join(root, {"pro-env": "pro", "applio-env": "applio-env", "edge": "edge"}[cid])


def python_path(root, cid="pro-env"):
    return os.path.join(env_dir(root, cid), ".venv", "bin", "python")


def weights_dir(root):
    return os.path.join(root, "weights")


def applio_dir(root):
    return os.path.join(root, "applio")


def training_dir(root):
    """Where Applio keeps voices being trained and their results (applio/logs points here). Survives updates."""
    return os.path.join(root, "training")


def seedvc_dir(root):
    return os.path.join(root, "seedvc")


def seedvc_env(root):
    """Environment of every Seed-VC process: its Hugging Face cache lives inside the engine folder."""
    return {"HF_HOME": os.path.join(seedvc_dir(root), "hf"), "PYTORCH_ENABLE_MPS_FALLBACK": "1"}


def python_for(root, cid, layout=None):
    """The interpreter a component runs in."""
    layout = layout or read_layout(root)
    if cid == "edge":
        return python_path(root, "edge")
    if cid in ("applio", "rvc-core", "rvc-fcpe") or cid.startswith("rvc-train"):
        return python_path(root, "applio-env" if layout == "split" else "pro-env")
    return python_path(root, "pro-env")


def state_dir(root, comp):
    cid, kind = comp["id"], comp["kind"]
    if kind == "env":
        return env_dir(root, cid)
    if kind == "edge":
        return env_dir(root, "edge")
    if kind == "ytdlp":
        return os.path.join(env_dir(root, "pro-env"), "ytdlp")
    if kind == "applio":
        return applio_dir(root)
    if kind == "weights":
        return os.path.join(root, "state", cid)
    if kind == "seedvc":
        return seedvc_dir(root)
    return os.path.join(root, "stems", cid[len("stems-"):], ".state")


def marker_path(root, comp):
    return os.path.join(state_dir(root, comp), "ready.json")


def installing_path(root, comp):
    return os.path.join(state_dir(root, comp), "installing.json")


def weight_files(root, comp):
    base = weights_dir(root) if comp["kind"] == "weights" else os.path.join(root, "stems", comp["id"][len("stems-"):])
    return [(os.path.join(base, e["path"]), e) for e in _entries(comp)]


# ------------------------------------------------------------------------------------------------- ready.json and state

def _read_json(path):
    try:
        with open(path) as f:
            data = json.load(f)
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def _atomic_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, sort_keys=True)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _remove(path):
    try:
        os.remove(path)
    except FileNotFoundError:
        pass


def _clear_ready(root, comp):
    _remove(marker_path(root, comp))


def _mark_installing(root, comp):
    _atomic_json(installing_path(root, comp), {"schema": SCHEMA, "id": comp["id"], "started": int(time.time())})


def _write_ready(root, comp, data):
    """The last step of an install: drops the installing marker, then writes ready.json."""
    _remove(installing_path(root, comp))
    data = dict(data, schema=SCHEMA, id=comp["id"], installed=int(time.time()))
    _atomic_json(marker_path(root, comp), data)


def _pro_pins():
    h = hashlib.sha256()
    for part in (pins.PRO_REQUIREMENTS, pins.PRO_CONSTRAINTS, " ".join(pins.PRO_STAGE2), " ".join(pins.PRO_STAGE3)):
        h.update(part.encode())
    return h.hexdigest()[:16]


def _executable(path):
    return os.path.isfile(path) and os.access(path, os.X_OK)


def _size(path):
    try:
        return os.stat(path).st_size
    except OSError:
        return None


def _wanted_version(comp):
    return {"env": _pro_pins, "applio": lambda: pins.APPLIO_COMMIT, "seedvc": lambda: pins.SEEDVC_COMMIT,
            "edge": lambda: EDGE_TTS}.get(comp["kind"], lambda: None)()


def _check(root, comp, marker, layout):
    """True when everything ready.json promises is still on disk and current."""
    kind = comp["kind"]
    if marker.get("schema") != SCHEMA:
        return False
    want = _wanted_version(comp)
    if want is not None and marker.get("version") != want:
        return False
    if kind in ("weights", "stems"):
        files = weight_files(root, comp)
        return all(_size(p) == e["size"] for p, e in files)
    if kind in ("env", "edge"):
        return _executable(python_path(root, comp["id"] if kind == "env" else "edge"))
    if kind == "ytdlp":
        return _executable(python_path(root, "pro-env"))
    if kind in ("applio", "seedvc"):
        base = applio_dir(root) if kind == "applio" else os.path.join(seedvc_dir(root), "seed-vc")
        sizes = marker.get("files")
        if not isinstance(sizes, dict) or not sizes:
            return False
        if any(_size(os.path.join(base, rel)) != n for rel, n in sizes.items()):
            return False
        if kind == "seedvc":
            return bool(marker.get("warmed"))
        return os.path.islink(os.path.join(base, "rvc", "models")) or os.path.isdir(os.path.join(base, "rvc", "models"))
    return False


def _has_traces(root, comp):
    if os.path.exists(installing_path(root, comp)):
        return True
    kind = comp["kind"]
    if kind in ("weights", "stems"):
        return any(os.path.exists(p) or os.path.exists(p + ".part") for p, _ in weight_files(root, comp))
    if kind == "ytdlp":
        return False
    return os.path.isdir(state_dir(root, comp)) and any(
        n != "ready.json" for n in os.listdir(state_dir(root, comp)))


def component_state(root, comp, layout=None):
    layout = layout or read_layout(root)
    marker = _read_json(marker_path(root, comp))
    if marker is not None:
        if os.path.exists(installing_path(root, comp)):
            return "partial"
        return "ready" if _check(root, comp, marker, layout) else "broken"
    return "partial" if _has_traces(root, comp) else "notinstalled"


def is_ready(root, component):
    layout = read_layout(root)
    comp = _by_id(layout).get(component)
    return comp is not None and component_state(root, comp, layout) == "ready"


def ytdlp_version(root):
    lib = os.path.join(env_dir(root, "pro-env"), ".venv", "lib")
    try:
        for py in os.listdir(lib):
            site = os.path.join(lib, py, "site-packages")
            if os.path.isdir(site):
                for name in os.listdir(site):
                    if name.lower().startswith("yt_dlp-") and name.endswith(".dist-info"):
                        return name[len("yt_dlp-"):-len(".dist-info")]
    except OSError:
        pass
    return None


def status(root):
    layout = read_layout(root)
    rows = []
    for c in components(layout):
        rows.append({"id": c["id"], "title": c["title"], "state": component_state(root, c, layout),
                     "download_bytes": c["download_bytes"], "disk_bytes": c["disk_bytes"], "license": c["license"],
                     "optional": c["optional"]})
    ready = {r["id"]: r["state"] == "ready" for r in rows}
    needed = ["pro-env", "applio", "rvc-core"] + (["applio-env"] if layout == "split" else [])
    return {"layout": layout, "ready": all(ready.get(n, False) for n in needed), "components": rows,
            "peak_gb": dict(PEAK_GB), "ytdlp_version": ytdlp_version(root)}


# ----------------------------------------------------------------------------------------------------------- download

class _HttpsOnlyRedirect(urllib.request.HTTPRedirectHandler):
    """Follows redirects (GitHub and Hugging Face send files to a CDN) but never away from https."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        _check_url(newurl, redirect=True)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _loopback(url):
    host = urllib.parse.urlsplit(url).hostname
    return host in ("127.0.0.1", "localhost", "::1")


def _check_url(url, redirect=False):
    low = url.lower()
    if low.startswith("https://") or (not redirect and low.startswith("http://") and _loopback(url)):
        return
    raise EngineError("The download address is not a secure (HTTPS) link, so nothing was downloaded.")


def _default_opener(req):
    try:
        import certifi
        ctx = ssl.create_default_context(cafile=certifi.where())
    except Exception:
        ctx = ssl.create_default_context()
    opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ctx), _HttpsOnlyRedirect())
    return opener.open(req, timeout=60)


def _hash_file(path, upto=None):
    h = hashlib.sha256()
    left = upto
    with open(path, "rb") as f:
        while left is None or left > 0:
            block = f.read(1 << 20 if left is None else min(1 << 20, left))
            if not block:
                break
            h.update(block)
            if left is not None:
                left -= len(block)
    return h


def download(url, dest, sha256, size, emit_fn=None, opener=None, max_bytes=2 << 30):
    """Downloads url to dest through dest + '.part', resuming a leftover .part with a Range request. The sha256 is
    checked before the file is moved into place; a mismatch deletes the .part. sha256/size may be None (a tarball
    whose files are hashed on extraction); max_bytes then bounds the download. emit_fn("progress", value=0..1)."""
    _check_url(url)
    opener = opener or _default_opener
    os.makedirs(os.path.dirname(os.path.abspath(dest)), exist_ok=True)
    if size is not None and os.path.exists(dest) and _size(dest) == size and (sha256 is None or _hash_file(dest).hexdigest() == sha256):
        return
    part = dest + ".part"
    limit = size if size is not None else max_bytes
    have = _size(part) or 0
    if have > limit or (size is not None and have == size and sha256 and _hash_file(part).hexdigest() != sha256):
        _remove(part)
        have = 0
    for attempt in (0, 1):
        headers = {"User-Agent": "Clone-n-Speak"}
        if have:
            headers["Range"] = "bytes=%d-" % have
        try:
            if size is not None and have == size:
                resp = None
            else:
                resp = opener(urllib.request.Request(url, headers=headers))
        except urllib.error.HTTPError as e:
            if e.code == 416 and have:   # the leftover is not a prefix of this file any more
                _remove(part)
                have = 0
                continue
            if e.code < 500:
                _remove(part)
            raise EngineError("The download server answered %d. Try again later." % e.code)
        except (OSError, http.client.HTTPException):
            raise EngineError(NO_CONNECTION)
        break
    digest = hashlib.sha256()
    done = start = 0
    expected = None
    try:
        if resp is not None:
            with resp:
                length = resp.headers.get("Content-Length")
                expected = int(length) if length and length.isdigit() else None
                status_code = getattr(resp, "status", None) or resp.getcode()
                if have and status_code == 206:
                    cr = resp.headers.get("Content-Range", "")
                    if not cr.startswith("bytes %d-" % have):
                        raise EngineError("The download server answered oddly. Press Install again.")
                    digest = _hash_file(part)
                    done = start = have
                    mode = "ab"
                else:   # 200: the server sent everything (or there was nothing to resume)
                    mode = "wb"
                with open(part, mode) as f:
                    while True:
                        try:
                            block = resp.read(1 << 20)
                        except http.client.IncompleteRead as cut:   # keep what arrived: the next Install resumes
                            f.write(cut.partial)
                            raise
                        if not block:
                            break
                        done += len(block)
                        if done > limit:
                            raise _Discard("The download is larger than expected, so it was stopped and deleted. "
                                           "Try again later.")
                        f.write(block)
                        digest.update(block)
                        if emit_fn is not None and size:
                            emit_fn("progress", value=min(1.0, done / float(size)))
        else:
            digest = _hash_file(part)
            done = have
    except _Discard as e:
        _remove(part)
        raise EngineError(str(e))
    except (OSError, http.client.HTTPException):
        raise EngineError(NO_CONNECTION)   # the .part stays: the next Install resumes it
    if (size is not None and done < size) or (expected is not None and done - start != expected):
        raise EngineError(NO_CONNECTION)   # the connection ended early: the .part stays and the next Install resumes it
    if size is not None and done != size:
        _remove(part)
        raise EngineError("The download has the wrong size and was deleted. Press Install again.")
    if sha256 is not None and digest.hexdigest() != sha256:
        _remove(part)
        raise EngineError("The download failed the checksum test and was deleted. Press Install again.")
    os.replace(part, dest)


class _Discard(Exception):
    pass


# ---------------------------------------------------------------------------------------------------------- extraction

def extract_pinned(tar_path, dest, file_pins):
    """Extracts only the files named in file_pins ({path below the archive's top folder: sha256}) into dest, checking
    each hash. Links, absolute paths and '..' reject the whole archive; other members are skipped."""
    seen = set()
    dest = os.path.realpath(dest)
    try:
        tar = tarfile.open(tar_path)
    except (tarfile.TarError, OSError) as e:
        raise EngineError("The downloaded archive is damaged (%s). Press Install again." % e)
    with tar:
        for m in tar:
            name = m.name
            parts = name.split("/")
            if name.startswith("/") or ".." in parts:
                raise EngineError("The archive has an unsafe path (%s) and was rejected." % name)
            if m.issym() or m.islnk() or m.isdev():
                raise EngineError("The archive has a link or device file (%s) and was rejected." % name)
            if not m.isfile() or len(parts) < 2:
                continue
            rel = "/".join(parts[1:])
            want = file_pins.get(rel)
            if want is None:
                continue
            target = os.path.realpath(os.path.join(dest, rel))
            if not target.startswith(dest + os.sep):
                raise EngineError("The archive has an unsafe path (%s) and was rejected." % name)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            h = hashlib.sha256()
            src = tar.extractfile(m)
            with open(target, "wb") as out:
                for block in iter(lambda: src.read(1 << 20), b""):
                    h.update(block)
                    out.write(block)
            if h.hexdigest() != want:
                raise EngineError("%s failed the checksum test; nothing was installed." % rel)
            seen.add(rel)
    missing = sorted(set(file_pins) - seen)
    if missing:
        raise EngineError("The archive is missing %d expected files (first: %s)." % (len(missing), missing[0]))


def extract_applio(tar_path, dest, file_pins=None):
    extract_pinned(tar_path, dest, pins.APPLIO_FILES if file_pins is None else file_pins)


def _swap_dir(new, final):
    old = final + ".old"
    shutil.rmtree(old, ignore_errors=True)
    if os.path.lexists(final):
        os.rename(final, old)
    os.rename(new, final)
    shutil.rmtree(old, ignore_errors=True)


def _sizes(base, rels):
    return {rel: os.path.getsize(os.path.join(base, rel)) for rel in rels}


# ------------------------------------------------------------------------------------------------------------ install

class _Progress:
    """Overall 0..1 progress over the components being installed, weighted by download size."""

    def __init__(self, emit_fn, comps):
        self.emit_fn = emit_fn
        self.map = cns_proto.ProgressMap([(c["id"], max(c["download_bytes"], 1)) for c in comps]) if comps else None
        self.stage = None

    def stage_at(self, cid, frac):
        self.emit_fn("progress", value=self.map.at(cid, frac))


def _closure(requested, layout):
    table = _by_id(layout)
    want = set()

    def add(cid):
        if cid not in table:
            raise EngineError("Unknown engine component: %s" % cid)
        for d in table[cid]["deps"]:
            add(d)
        want.add(cid)
    for cid in requested:
        add(cid)
    return [c for c in components(layout) if c["id"] in want]


def _run_uv(args, env, emit_fn, prog, cid, lo, hi, what):
    emit_fn("status", msg=what)
    try:
        p = subprocess.Popen(args, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    except OSError as e:
        raise EngineError("Could not start the installer (%s)." % e)
    n = 0
    try:
        for line in p.stdout:
            n += 1
            print(line.rstrip(), file=sys.stderr, flush=True)
            prog.stage_at(cid, lo + (hi - lo) * (1 - 0.97 ** n))
        code = p.wait()
    except BaseException:
        p.kill()
        raise
    if code:
        raise EngineError("Could not install %s — see the log, then press Install again." % what.rstrip("…. "))


def _check_disk(root, comps):
    need = sum(c["disk_bytes"] for c in comps)
    probe = root
    while not os.path.exists(probe):
        probe = os.path.dirname(probe)
    free = shutil.disk_usage(probe).free
    if free < need * 1.1:
        raise EngineError("Not enough free disk space: %.1f GB needed, %.1f GB free." % (need / 1e9, free / 1e9))


def _uv_env(env):
    return dict(os.environ, **(env or {}))


def _write_temp(root, name, text):
    os.makedirs(root, exist_ok=True)
    path = os.path.join(root, name)
    with open(path, "w") as f:
        f.write(text)
    return path


def _install_env(root, comp, uv, uvenv, emit_fn, prog, python):
    cid = comp["id"]
    base = env_dir(root, cid)
    py = python_path(root, cid)
    os.makedirs(base, exist_ok=True)
    if not _executable(py):
        shutil.rmtree(os.path.join(base, ".venv"), ignore_errors=True)
        _run_uv([uv, "venv", "--relocatable", "--python", python, os.path.join(base, ".venv")], uvenv, emit_fn, prog,
                cid, 0.0, 0.03, "Python environment…")
    if cid == "applio-env":
        # the strict set is Applio's exact freeze: it is both the requirements and the constraints
        cons = _write_temp(base, "constraints.txt", pins.APPLIO_STRICT_CONSTRAINTS)
        _run_uv([uv, "pip", "install", "--python", py, "-r", cons, "-c", cons], uvenv, emit_fn, prog, cid, 0.03, 1.0,
                "Applio environment (~1.3 GB)…")
        return {"python": py, "version": _wanted_version(comp)}
    req = _write_temp(base, "requirements.txt", pins.PRO_REQUIREMENTS)
    cons = _write_temp(base, "constraints.txt", pins.PRO_CONSTRAINTS)
    _run_uv([uv, "pip", "install", "--python", py, "-r", req, "-c", cons], uvenv, emit_fn, prog, cid, 0.03, 0.85,
            "PyTorch and audio libraries (~1.3 GB)…")
    _run_uv([uv, "pip", "install", "--python", py, "--no-deps", "-c", cons] + list(pins.PRO_STAGE2), uvenv, emit_fn, prog,
            cid, 0.85, 0.92, "Audio tools…")
    _run_uv([uv, "pip", "install", "--python", py, "-c", cons] + list(pins.PRO_STAGE3), uvenv, emit_fn, prog, cid, 0.92,
            1.0, "Helper libraries…")
    return {"python": py, "version": _wanted_version(comp), "torch": "2.8.0"}


def _install_weights(root, comp, emit_fn, prog, opener):
    entries = weight_files(root, comp)
    total = sum(e["size"] for _, e in entries) or 1
    done_before = 0
    for path, e in entries:
        base = done_before

        def sub(event, value=0.0, _b=base, **_):
            prog.stage_at(comp["id"], (_b + value * e["size"]) / total)
        emit_fn("status", msg="Downloading %s…" % os.path.basename(path))
        download(e["url"], path, e["sha256"], e["size"], sub, opener)
        done_before += e["size"]
    return {"files": {e["path"]: e["size"] for _, e in entries}}


def _install_applio(root, comp, emit_fn, prog, opener):
    tmp = os.path.join(root, "applio.download")
    new = os.path.join(root, "applio.new")
    os.makedirs(root, exist_ok=True)
    tar_path = os.path.join(tmp, "applio.tar.gz")
    emit_fn("status", msg="Downloading Applio…")
    download(pins.APPLIO_URL, tar_path, None, None, None, opener, max_bytes=200 << 20)
    prog.stage_at(comp["id"], 0.7)
    shutil.rmtree(new, ignore_errors=True)
    os.makedirs(new)
    try:
        extract_applio(tar_path, new)
        # logs/ holds voices being trained and the silent clips training mixes in: it lives outside applio/, so
        # updating Applio never touches the user's voices.
        logs = os.path.join(new, "logs")
        train = training_dir(root)
        os.makedirs(train, exist_ok=True)
        if os.path.isdir(logs):
            for name in os.listdir(logs):
                dest = os.path.join(train, name)
                shutil.rmtree(dest, ignore_errors=True)
                shutil.move(os.path.join(logs, name), dest)
            os.rmdir(logs)
        os.symlink(os.path.join("..", "training"), logs)
        os.makedirs(weights_dir(root), exist_ok=True)
        models = os.path.join(new, "rvc", "models")
        shutil.rmtree(models, ignore_errors=True)
        os.symlink(os.path.join("..", "..", "weights"), models)   # rvc/models/predictors etc. are the weights folder
        for sub in ("embedders/embedders_custom", "formant", "pretraineds/custom", "predictors", "embedders/contentvec",
                    "pretraineds/hifi-gan"):
            os.makedirs(os.path.join(weights_dir(root), sub), exist_ok=True)
        files = _sizes(new, [r for r in pins.APPLIO_FILES if not r.startswith("logs/")])
        # keep ready.json out of the swap: it is written after, by _write_ready
        _swap_dir(new, applio_dir(root))
    except BaseException:
        shutil.rmtree(new, ignore_errors=True)
        raise
    shutil.rmtree(tmp, ignore_errors=True)
    return {"version": pins.APPLIO_COMMIT, "files": files}


def _warm_seedvc(root, py, src, uvenv, emit_fn):
    """Converts a second of noise once so Seed-VC fetches its models (~1.6 GB) into the engine's HF cache."""
    import struct
    import wave
    import random
    tmp = os.path.join(seedvc_dir(root), "warmup")
    shutil.rmtree(tmp, ignore_errors=True)
    os.makedirs(tmp)
    wav = os.path.join(tmp, "noise.wav")
    rnd = random.Random(0)
    with wave.open(wav, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(22050)
        w.writeframes(b"".join(struct.pack("<h", rnd.randint(-300, 300)) for _ in range(22050)))
    cmd = [py, "inference.py", "--source", wav, "--target", wav, "--output", tmp, "--diffusion-steps", "4",
           "--length-adjust", "1.0", "--inference-cfg-rate", "0.7", "--fp16", "False"]
    env = dict(uvenv, **seedvc_env(root))
    emit_fn("status", msg="Downloading Seed-VC models (~1.6 GB)…")
    run = subprocess.run(cmd, cwd=src, capture_output=True, text=True, env=env)
    ok = run.returncode == 0 and any(n.endswith(".wav") and n != "noise.wav" for n in os.listdir(tmp))
    if not ok:
        print(run.stdout[-2000:], run.stderr[-6000:], file=sys.stderr, flush=True)
    shutil.rmtree(tmp, ignore_errors=True)
    if not ok:
        raise EngineError("Seed-VC could not fetch its models — check the network and press Install again.")


def _install_seedvc(root, comp, uvenv, emit_fn, prog, opener):
    base = seedvc_dir(root)
    tmp = os.path.join(base, "download")
    new = os.path.join(base, "seed-vc.new")
    os.makedirs(base, exist_ok=True)
    tar_path = os.path.join(tmp, "seedvc.tar.gz")
    emit_fn("status", msg="Downloading Seed-VC…")
    download(pins.SEEDVC_URL, tar_path, None, None, None, opener, max_bytes=300 << 20)
    prog.stage_at(comp["id"], 0.05)
    shutil.rmtree(new, ignore_errors=True)
    os.makedirs(new)
    try:
        extract_pinned(tar_path, new, pins.SEEDVC_FILES)
        _swap_dir(new, os.path.join(base, "seed-vc"))
    except BaseException:
        shutil.rmtree(new, ignore_errors=True)
        raise
    shutil.rmtree(tmp, ignore_errors=True)
    src = os.path.join(base, "seed-vc")
    _warm_seedvc(root, python_path(root, "pro-env"), src, uvenv, emit_fn)
    return {"version": pins.SEEDVC_COMMIT, "files": _sizes(src, pins.SEEDVC_FILES), "warmed": True,
            "hf_home": seedvc_env(root)["HF_HOME"]}


