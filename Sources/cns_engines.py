"""The pro-engine manager: installs, checks and removes the heavy engines (RVC, Seed-VC, stems, Edge, yt-dlp).

Stdlib only, Python 3.9+. Every download is pinned (see cns_pins.py, generated by tools/pin_applio.py), resumable and
checked against its sha256 before it is moved into place. A component counts as installed only when its ready.json
exists: it is removed first when an install or uninstall starts and written last, so a killed install is never
mistaken for a finished one.

CLI (events on the cns_proto line protocol; arguments, or ONE JSON request line on stdin):
    cns_engines.py status|install|weights|uninstall|update-ytdlp|memory  [--root DIR] [--components a,b] [--uv PATH]
"""
